/**
 * Normalizes a name string by removing accents, symbols, and extra whitespace.
 */
function normalizeName(input: string): string {
  return input
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/['’`\-_.]/g, '') // strip punctuation like O'Neal -> Oneal
    .replace(/[^a-z0-9\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Checks if a given name is an NBA player name, alias, or contains a distinctive NBA name.
 * Returns true if the name is an NBA name (violates the rule).
 */
export function isNbaName(name: string): boolean {
  if (!name || typeof name !== 'string') return false;

  const clean = normalizeName(name);
  if (!clean) return false;

  const words = clean.split(' ').filter(Boolean);

  // 1. Check if any word in the name is a distinctive NBA star/legend name
  for (const word of words) {
    if (DISTINCTIVE_NBA_NAMES.has(word)) {
      return true;
    }
  }

  // 2. Check against full NBA names
  for (const nbaName of NBA_FULL_NAMES) {
    const cleanNba = normalizeName(nbaName);

    // Exact match
    if (clean === cleanNba) {
      return true;
    }

    // Contains whole NBA name as a phrase (e.g. "lebron james jr", "stephen curry 30")
    if (clean.includes(cleanNba)) {
      return true;
    }

    // Check if name has all tokens of the NBA name
    const nbaTokens = cleanNba.split(' ').filter(Boolean);
    if (nbaTokens.length >= 2) {
      const allTokensPresent = nbaTokens.every((token) => words.includes(token));
      if (allTokensPresent) {
        return true;
      }
    }
  }

  return false;
}

